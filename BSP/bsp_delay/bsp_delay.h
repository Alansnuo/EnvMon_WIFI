#ifndef __BSP_DELAY_H
#define __BSP_DELAY_H

#include <stdint.h>

/* ========================= 毫秒级延时 (所有驱动共用) =========================
 *
 * 驱动里不要直接写 HAL_Delay, 一律调这个. 原因:
 *
 *   HAL_Delay 是"忙等" —— 抱着 CPU 空转. 裸机时无所谓, 但上了 FreeRTOS,
 *   一个任务卡在 HAL_Delay(1000) 里, 低优先级任务整整 1 秒得不到执行.
 *   可驱动又不能直接改成 vTaskDelay —— 那样裸机工程就编不过了.
 *
 * 所以这里只留一个声明, 实现拆成两份, 由链接器挑:
 *
 *   BSP/bsp_delay.c    弱定义(__weak), 内容是 HAL_Delay    ← 裸机 / 兜底
 *   APP/app_delay.c    强定义,          内容是 vTaskDelay   ← 上了 FreeRTOS
 *
 * 链接器规则:**强符号覆盖弱符号**. 两个都加进工程 → 用 APP 那份;
 * 只带 BSP 那份去裸机工程 → 用 HAL_Delay, 一个字都不用改.
 *
 * 这就是"驱动不依赖 RTOS, 但在 RTOS 下又不会饿死别人"的实现方式 ——
 * 驱动只管"要延时", 谁来延、怎么延, 是上层的事.
 *
 * ⚠️ 本头文件故意只 include <stdint.h>, 不 include "main.h".
 *    这样驱动带着它就能移植到别的芯片, 不用把 STM32 的头文件一起搬.
 *
 * ⚠️ 上了 FreeRTOS 的工程, 必须把 APP/app_delay.c 也加进去.
 *    忘了加**不会报错**(走弱定义照样链接通过), 只是延时悄悄变回忙等.
 * ============================================================================ */

/* 延时 ms 毫秒.
 *   裸机 / 调度器启动前  → 忙等, 时间精确;
 *   任务里(调度器已运行) → 挂起本任务让出 CPU, 实际时长 >= ms (最多多一个 tick). */
void BSP_DelayMs(uint32_t ms);

#endif /* __BSP_DELAY_H */
